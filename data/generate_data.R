# =============================================================================
# generate_data.R -- simulated data and answer key for the RD exercise
# "Pflegegrad 3 und die Arbeitszeit pflegender Angehoeriger"
#
# Run from the repository root:   Rscript data/generate_data.R
# Writes: data.csv, data.js (repository root; data.js is loaded by the app)
#         ../logs/rdd_pflegegrad_answer_key.log (answer key, outside the repo)
#
# Setting (stylised, simulated): long-term care assessment (Begutachtung) yields
# a score X between 0 and 100 (Paragraph 15 SGB XI). Care grade 3 (Pflegegrad 3)
# from 47.5 points, care grade 2 from 27 to below 47.5, care grade 4 from 70.
# Sample: X in [27, 70), so only grades 2 and 3 occur (sharp RD at c = 47.5).
# Outcome Y: weekly working hours of the main informal caregiver.
# Covariate W: age of the caregiver (predetermined, smooth in X, no jump).
#
# DGP (xc = X - 47.5, D = 1[X >= 47.5]):
#   Y = 24 - 0.30*xc + 0.0004*xc^3 - 3*D + e,   e ~ N(0, 3.5^2)
#   W = 52 + 0.15*xc + u,                         u ~ N(0, 7^2)
# True effect tau = -3 hours. The cubic term makes wide bandwidths visibly biased.
# Scenario B (manipulation, histogram only): 60 % of units with X in [45.5, 47.5)
# are moved to [47.5, 48.5). (40 % moved too few units for a visible spike.)
# X and Y are rounded BEFORE D is assigned and before any estimation.
#
# Seed 20261118, fixed before calibration. Parameters were chosen on this seed to
# meet the design targets (naive gap at least twice tau; local linear estimate at
# the teaching bandwidth close to tau; wide bandwidth visibly biased; no placebo
# jump). Packages: R 4.5.2, rdrobust 4.1.1.
# =============================================================================

suppressMessages(library(rdrobust))

log_path <- file.path("..", "logs", "rdd_pflegegrad_answer_key.log")
dir.create(dirname(log_path), showWarnings = FALSE)
sink(log_path, split = TRUE)

cat("Answer key, RD exercise Pflegegrad (generated by data/generate_data.R)\n")
cat("R:", R.version.string, "| rdrobust:", as.character(packageVersion("rdrobust")), "\n")
cat("Date:", format(Sys.Date()), "\n\n")

# --- 1. Data ------------------------------------------------------------------
set.seed(20261118)
N   <- 1200
cc  <- 47.5
tau <- -3

x  <- round(runif(N, 27, 69.95), 1)          # round first, keeps X < 70
e  <- rnorm(N, 0, 3.5)
u  <- rnorm(N, 0, 7)
d  <- as.integer(x >= cc)                     # then assign treatment
xc <- x - cc
y  <- round(24 - 0.30 * xc + 0.0004 * xc^3 + tau * d + e, 1)
w  <- round(52 + 0.15 * xc + u, 0)

# Scenario B (manipulation): move 60 % of units just below the cut-off above it
xb   <- x
near <- which(x >= 45.5 & x < cc)
move <- near[runif(length(near)) < 0.60]
xb[move] <- round(cc + runif(length(move), 0, 0.99), 1)

stopifnot(all(x >= 27 & x < 70), all(xb >= 27 & xb < 70), all(y > 0))

# --- 2. Answer key --------------------------------------------------------------
# local linear regression, triangular kernel, |X - c| < h, treated side X >= c
side_fit <- function(v, h, right) {
  s <- if (right) xc >= 0 & abs(xc) < h else xc < 0 & abs(xc) < h
  k <- 1 - abs(xc[s]) / h
  f <- lm(v[s] ~ xc[s], weights = k)
  c(intercept = unname(coef(f)[1]), slope = unname(coef(f)[2]), n = sum(s))
}
rd_est <- function(v, h) {
  side_fit(v, h, TRUE)["intercept"] - side_fit(v, h, FALSE)["intercept"]
}
key <- function(name, value, digits = 6) {
  cat(sprintf("KEY %-16s = %.*f\n", name, digits, value))
}

cat("--- Sample\n")
key("N", N, 0); key("n_left", sum(d == 0), 0); key("n_right", sum(d == 1), 0)

cat("\n--- Step 5: naive comparison (full sample)\n")
key("mean_left", mean(y[d == 0]))
key("mean_right", mean(y[d == 1]))
key("naive", mean(y[d == 1]) - mean(y[d == 0]))
print(summary(lm(y ~ d))$coefficients)

cat("\n--- Teaching bandwidth: MSE-optimal (rdbwselect, mserd), rounded\n")
bw  <- rdbwselect(y, x, c = cc, kernel = "triangular", p = 1, bwselect = "mserd")
hT  <- round(bw$bws[1])
key("h_mse", bw$bws[1]); key("h_teach", hT, 0)

cat("\n--- Step 7: local linear estimate at h_teach\n")
L <- side_fit(y, hT, FALSE); R <- side_fit(y, hT, TRUE)
key("icpt_left", L["intercept"]); key("slope_left", L["slope"])
key("icpt_right", R["intercept"]); key("slope_right", R["slope"])
key("n_left_h", L["n"], 0); key("n_right_h", R["n"], 0)
key("rd_teach", rd_est(y, hT))
k  <- pmax(0, 1 - abs(xc) / hT)
fi <- lm(y ~ d * xc, weights = k, subset = abs(xc) < hT)
cat("Pooled regression with interaction, coefficient on d:\n")
print(summary(fi)$coefficients["d", ])
rr <- rdrobust(y, x, c = cc, h = hT, kernel = "triangular", p = 1)
cat("rdrobust conventional estimate (must equal rd_teach):\n")
key("rdrobust_conv", rr$coef[1]); key("rdrobust_se", rr$se[1])
cat(sprintf("rdrobust robust 95%% CI: [%.4f, %.4f]\n", rr$ci[3, 1], rr$ci[3, 2]))
stopifnot(abs(rr$coef[1] - rd_est(y, hT)) < 1e-6)

cat("\n--- Step 8: estimates by bandwidth (slider)\n")
for (h in c(2, 3, 5, 8, 10, 15, 20)) {
  cat(sprintf("h = %4.1f  n = %4d  estimate = %8.4f\n", h,
              side_fit(y, h, FALSE)["n"] + side_fit(y, h, TRUE)["n"], rd_est(y, h)))
}
key("rd_h20", rd_est(y, 20)); key("rd_h3", rd_est(y, 3))

cat("\n--- Step 9: density, units per point around the cut-off (bins aligned at c)\n")
tabA <- table(cut(x,  breaks = seq(43.5, 51.5, 1), right = FALSE))
tabB <- table(cut(xb, breaks = seq(43.5, 51.5, 1), right = FALSE))
print(rbind(A = tabA, B = tabB))
key("moved_B", length(move), 0)

cat("\n--- Step 10: placebo, caregiver age W at h_teach\n")
key("placebo_teach", rd_est(w, hT))
pw <- rdrobust(w, x, c = cc, h = hT, kernel = "triangular", p = 1)
cat(sprintf("rdrobust placebo: estimate %.4f, robust p-value %.4f\n", pw$coef[1], pw$pv[3]))

sink()

# --- 3. Export ------------------------------------------------------------------
write.csv(data.frame(x = sprintf("%.1f", x), y = sprintf("%.1f", y), w = w, d = d),
          "data.csv", row.names = FALSE, quote = FALSE)

js <- c(
  "// Generated by data/generate_data.R (seed 20261118). Do not edit by hand.",
  "// DATA rows: [x = Punktzahl der Begutachtung, y = Wochenarbeitsstunden, w = Alter der Pflegeperson]",
  "const DATA = [",
  paste0("[", sprintf("%.1f", x), ",", sprintf("%.1f", y), ",", w, "],"),
  "];",
  "// Scenario B (manipulation): running variable only",
  paste0("const DATA_B_X = [", paste(sprintf("%.1f", xb), collapse = ","), "];"),
  "// Answer key, identical to KEY lines in logs/rdd_pflegegrad_answer_key.log",
  "const KEY = {",
  sprintf("  cutoff: %.1f, hTeach: %d, tauTrue: %d,", cc, hT, tau),
  sprintf("  meanLeft: %.6f, meanRight: %.6f, naive: %.6f,",
          mean(y[d == 0]), mean(y[d == 1]), mean(y[d == 1]) - mean(y[d == 0])),
  sprintf("  icptLeft: %.6f, icptRight: %.6f, rdTeach: %.6f,",
          L["intercept"], R["intercept"], rd_est(y, hT)),
  sprintf("  rdH20: %.6f, placeboTeach: %.6f", rd_est(y, 20), rd_est(w, hT)),
  "};"
)
writeLines(js, "data.js", useBytes = TRUE)
cat("Wrote data.csv, data.js and", log_path, "\n")
